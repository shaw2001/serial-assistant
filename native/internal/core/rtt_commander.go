// Bidirectional RTT through J-Link Commander and J-Link's RTT Telnet server.
//
// JLink.exe connects with -AutoConnect 1, runs a small generated command file
// (RTT control-block address / search range when configured) and then waits
// for input on our open stdin pipe, so the J-Link connection stays up.
// "Connected" means the RTT Telnet port accepts a connection: we poll it from
// the moment JLink.exe starts. Commander's stdout is only watched in parallel
// for errors (its prompt is not a reliable signal and may never be flushed). While it is connected the J-Link DLL serves RTT on
// 127.0.0.1:<RTTTelnetPort>: what we read is up-channel data, what we write
// goes to the down-channel (channel 0 unless a SEGGER TELNET config string
// selects another channel within 100 ms of connecting).

// CommanderArgs is the JLink.exe command line; the command file is last.
func (r RTTOptions) CommanderArgs(port int, script string) []string {
	a := []string{"-Device", r.Device, "-If", r.Iface, "-Speed", strconv.Itoa(r.Speed)}
	if r.Serial != "" {
		a = append(a, "-USB", r.Serial)
	}
	return append(a, "-AutoConnect", "1", "-ExitOnError", "1", "-NoGui", "1", "-RTTTelnetPort", strconv.Itoa(port), "-CommandFile", script)
}

// CommanderScript is the generated J-Link command file (ASCII only).
func (r RTTOptions) CommanderScript(port int) string {
	lines := []string{
		"// Generated by SerialAssistant for a J-Link RTT session.",
		"// The target is connected by -AutoConnect 1. After this file J-Link Commander",
		fmt.Sprintf("// stays connected; RTT channel %d is served on 127.0.0.1:%d (RTT Telnet).", r.Channel, port),
	}
	switch r.AddrMode {
	case "address":
		lines = append(lines, "exec SetRTTAddr "+r.Address)
	case "ranges":
		lines = append(lines, "exec SetRTTSearchRanges "+r.Ranges)
	}
	return strings.Join(lines, "\r\n") + "\r\n"
}

// TelnetConfig selects a non-default RTT channel; channel 0 needs nothing.
func (r RTTOptions) TelnetConfig() string {
	if r.Channel == 0 {
		return ""
	}
	return fmt.Sprintf("$$SEGGER_TELNET_ConfigStr=RTTCh;%d$$", r.Channel)
}

// portBusy reports whether something already listens on, or holds, the port.
var portBusy = func(port int) bool {
	addr := "127.0.0.1:" + strconv.Itoa(port)
	if c, e := net.DialTimeout("tcp", addr, 150*time.Millisecond); e == nil {
		c.Close()
		return true
	}
	l, e := net.Listen("tcp", addr)
	if e != nil {
		return true
	}
	l.Close()
	return false
}

// pickTelnetPort returns want, or the next free port when want is busy.
func pickTelnetPort(want int) (int, error) {
	for p := want; p < want+50 && p <= 65535; p++ {
		if !portBusy(p) {
			return p, nil
		}
	}
	return 0, fmt.Errorf("RTT Telnet 端口 %d–%d 都被占用，请在设置中换一个端口。", want, want+49)
}

var (
	// commanderConnectTimeout is only a failure cutoff while JLink.exe keeps
	// running but its RTT Telnet port never becomes reachable.
	commanderConnectTimeout = 30 * time.Second
	telnetPollInterval      = 250 * time.Millisecond
	telnetBannerWait        = 400 * time.Millisecond
)

// stripTelnetBanner removes J-Link's greeting ("SEGGER J-Link … Real time
// terminal output", probe line, "Process: …") from the start of the stream.
// done is false while the greeting may still be incomplete.
func stripTelnetBanner(buf []byte) (banner []string, rest []byte, done bool) {
	if !bytes.HasPrefix(buf, []byte("SEGGER J-Link")) {
		if len(buf) < len("SEGGER J-Link") && bytes.HasPrefix([]byte("SEGGER J-Link"), buf) {
			return nil, buf, false
		}
		return nil, buf, true
	}
	rest = buf
	for len(banner) < 4 {
		i := bytes.IndexByte(rest, '\n')
		if i < 0 {
			return banner, rest, false
		}
		line := strings.TrimRight(string(rest[:i]), "\r")
		rest = rest[i+1:]
		banner = append(banner, line)
		if strings.HasPrefix(line, "Process:") {
			return banner, rest, true
		}
	}
	return banner, rest, true
}

type commanderPort struct {
	cmd     *exec.Cmd
	stdin   io.WriteCloser
	script  string
	port    int
	device  string
	started time.Time
	idle    time.Duration

	mu      sync.Mutex
	status  []string
	tail    []string
	partial string
	lastOut time.Time
	emitted int
	ready   bool
	failed  bool
	conn    net.Conn
	pending []byte
	in, out uint64

	failCh    chan struct{}
	exited    chan struct{}
	outDone   chan struct{}
	closed    chan struct{}
	closeOnce sync.Once
	exitErr   error
}

func startCommander(exe string, o RTTOptions) (Port, error) {
	want := o.telnetPort()
	port, e := pickTelnetPort(want)
	if e != nil {
		RTTDiag("rtt telnet port: %v", e)
		return nil, e
	}
	script, e := rttTempFile("jlink", ".jlink")
	if e != nil {
		return nil, e
	}
	body := o.CommanderScript(port)
	if e := os.WriteFile(script, []byte(body), 0600); e != nil {
		return nil, fmt.Errorf("无法写入 J-Link 命令文件：%v", e)
	}
	args := o.CommanderArgs(port, script)
	cmd := exec.Command(exe, args...)
	cmd.Dir = filepath.Dir(exe)
	prepareRTTCmd(cmd)
	stdin, e := cmd.StdinPipe()
	if e != nil {
		os.Remove(script)
		return nil, e
	}
	r, w, e := os.Pipe()
	if e != nil {
		os.Remove(script)
		return nil, e
	}
	cmd.Stdout, cmd.Stderr = w, w
	RTTDiag("rtt commander start: %s", CommandLine(exe, args))
	RTTDiag("rtt commander script: %s", strings.ReplaceAll(strings.TrimSpace(body), "\r\n", " | "))
	RTTDiag("rtt telnet port=%d (configured %d)", port, want)
	if e := cmd.Start(); e != nil {
		r.Close()
		w.Close()
		os.Remove(script)
		RTTDiag("rtt commander start failed: %v", e)
		return nil, fmt.Errorf("无法启动 %s：%v", filepath.Base(exe), e)
	}
	w.Close()
	p := &commanderPort{cmd: cmd, stdin: stdin, script: script, port: port, device: o.Device, started: time.Now(), lastOut: time.Now(), idle: rttPromptIdle,
		failCh: make(chan struct{}), exited: make(chan struct{}), outDone: make(chan struct{}), closed: make(chan struct{})}
	if port != want {
		p.pushStatus(fmt.Sprintf("RTT Telnet 端口 %d 已被占用，改用 %d。", want, port))
	}
	go p.readOutput(r)
	go p.watchPrompt()
	go func() {
		<-p.outDone
		p.exitErr = cmd.Wait()
		close(p.exited)
	}()
	if e := p.connect(o); e != nil {
		return nil, e
	}
	return p, nil
}

// connect polls the RTT Telnet port right away and returns as soon as it
// accepts. Commander errors or an early exit end the wait immediately.
func (p *commanderPort) connect(o RTTOptions) error {
	addr := "127.0.0.1:" + strconv.Itoa(p.port)
	deadline := p.started.Add(commanderConnectTimeout)
	attempts := 0
	var last error
	for {
		select {
		case <-p.failCh:
			return p.fail("connect error")
		case <-p.exited:
			return p.fail("commander exited")
		default:
		}
		attempts++
		c, e := net.DialTimeout("tcp", addr, 300*time.Millisecond)
		if e == nil {
			p.mu.Lock()
			p.ready = true // later Commander output can no longer fail the connect
			p.mu.Unlock()
			p.handshake(c, o)
			RTTDiag("rtt connected via telnet poll after=%dms attempts=%d", time.Since(p.started).Milliseconds(), attempts)
			return nil
		}
		last = e
		if time.Now().After(deadline) {
			RTTDiag("rtt telnet %s not reachable after %s (%d attempts): %v", addr, commanderConnectTimeout, attempts, last)
			p.Close()
			p.mu.Lock()
			lines := append([]string{}, p.tail...)
			p.mu.Unlock()
			msg := fmt.Sprintf("J-Link Commander 已运行 %d 秒，但 RTT Telnet 服务 %s 仍无法连接（%v）。请检查 J-Link 与目标板的连接，确认端口没有被防火墙或其他程序拦截，或在设置中换一个端口。", int(commanderConnectTimeout/time.Second), addr, last)
			if len(lines) > 0 {
				from := len(lines) - 4
				if from < 0 {
					from = 0
				}
				msg += " J-Link 输出：" + strings.Join(lines[from:], " / ")
			}
			return errors.New(msg)
		}
		select {
		case <-p.failCh:
			return p.fail("connect error")
		case <-p.exited:
			return p.fail("commander exited")
		case <-time.After(telnetPollInterval):
		}
	}
}

// handshake selects a non-default channel within J-Link's 100 ms window and
// keeps the greeting out of the received data.
func (p *commanderPort) handshake(conn net.Conn, o RTTOptions) {
	addr := conn.RemoteAddr().String()
	if cfg := o.TelnetConfig(); cfg != "" {
		_, _ = conn.Write([]byte(cfg))
		RTTDiag("rtt telnet config sent: %s", cfg)
	}
	var head []byte
	buf := make([]byte, 1024)
	until := time.Now().Add(telnetBannerWait)
	for time.Now().Before(until) && len(head) < 2048 {
		_ = conn.SetReadDeadline(until)
		n, e := conn.Read(buf)
		head = append(head, buf[:n]...)
		if _, _, done := stripTelnetBanner(head); done && len(head) > 0 {
			break
		}
		if e != nil {
			break
		}
	}
	_ = conn.SetReadDeadline(time.Time{})
	banner, rest, _ := stripTelnetBanner(head)
	p.mu.Lock()
	for _, l := range banner {
		p.status = append(p.status, "J-Link RTT Telnet："+l)
	}
	p.status = append(p.status, fmt.Sprintf("RTT Telnet 已连接 %s（用时 %d ms）：接收上行通道 %d，发送写入下行通道 %d。", addr, time.Since(p.started).Milliseconds(), o.Channel, o.Channel))
	p.pending = append([]byte(nil), rest...)
	p.in += uint64(len(rest))
	p.conn = conn
	p.mu.Unlock()
	RTTDiag("rtt telnet connected %s banner=%q", addr, strings.Join(banner, " | "))
}

func (p *commanderPort) readOutput(r *os.File) {
	defer close(p.outDone)
	defer r.Close()
	buf := make([]byte, 4096)
	for {
		n, e := r.Read(buf)
		if n > 0 {
			p.mu.Lock()
			p.lastOut = time.Now()
			text := p.partial + string(buf[:n])
			for {
				i := strings.IndexAny(text, "\r\n")
				if i < 0 {
					break
				}
				p.lineLocked(text[:i])
				text = text[i+1:]
			}
			p.partial = text
			p.mu.Unlock()
		}
		if e != nil {
			p.mu.Lock()
			if p.partial != "" {
				p.lineLocked(p.partial)
				p.partial = ""
			}
			p.mu.Unlock()
			return
		}
	}
}

func (p *commanderPort) lineLocked(line string) {
	line = strings.TrimSpace(line)
	if line == "" || line == "J-Link>" || strings.Trim(line, "-=*") == "" {
		return
	}
	p.tail = append(p.tail, line)
	if len(p.tail) > 16 {
		p.tail = p.tail[1:]
	}
	RTTDiag("rtt commander: %s", line)
	if p.emitted < 200 {
		p.emitted++
		p.status = append(p.status, "J-Link："+line)
	}
	if !p.ready && !p.failed && looksLikeJLinkError(strings.ToLower(line)) {
		p.failed = true
		close(p.failCh)
	}
}

// commanderQuestion matches the setting questions J-Link Commander asks when
// it rejects a command-line value (e.g. an unknown device name).
var commanderQuestion = regexp.MustCompile(`(?i)(device|tif|interface|speed)\s*>$`)

// watchPrompt reports such a question (left idle without a newline) as a
// connect error instead of answering it. It never gates success.
func (p *commanderPort) watchPrompt() {
	t := time.NewTicker(50 * time.Millisecond)
	defer t.Stop()
	for {
		select {
		case <-p.exited:
			return
		case <-p.closed:
			return
		case <-t.C:
		}
		p.mu.Lock()
		prompt := strings.TrimSpace(p.partial)
		if !p.ready && !p.failed && commanderQuestion.MatchString(prompt) && time.Since(p.lastOut) > p.idle {
			p.tail = append(p.tail, prompt)
			RTTDiag("rtt commander asks: %s", prompt)
			p.failed = true
			close(p.failCh)
		}
		p.mu.Unlock()
	}
}

func (p *commanderPort) pushStatus(s string) {
	p.mu.Lock()
	p.status = append(p.status, s)
	p.mu.Unlock()
}

func (p *commanderPort) TakeStatus() []string {
	p.mu.Lock()
	defer p.mu.Unlock()
	s := p.status
	p.status = nil
	return s
}

func (p *commanderPort) exitCode() int {
	if p.cmd.ProcessState != nil {
		return p.cmd.ProcessState.ExitCode()
	}
	return -1
}

func (p *commanderPort) fail(why string) error {
	p.Close()
	p.mu.Lock()
	lines := append([]string{}, p.tail...)
	p.mu.Unlock()
	msg := explainJLink(lines, p.device, p.exitCode())
	RTTDiag("rtt commander connect failed (%s) exit=%d: %s", why, p.exitCode(), msg)
	return errors.New(msg)
}

func (p *commanderPort) Read(b []byte) (int, error) {
	p.mu.Lock()
	if len(p.pending) > 0 {
		n := copy(b, p.pending)
		p.pending = p.pending[n:]
		p.mu.Unlock()
		return n, nil
	}
	conn := p.conn
	p.mu.Unlock()
	select {
	case <-p.closed:
		return 0, errRTTClosed
	default:
	}
	_ = conn.SetReadDeadline(time.Now().Add(100 * time.Millisecond))
	n, e := conn.Read(b)
	if n > 0 {
		p.mu.Lock()
		p.in += uint64(n)
		p.mu.Unlock()
		return n, nil
	}
	if ne, ok := e.(net.Error); ok && ne.Timeout() {
		select {
		case <-p.exited:
			return 0, p.exitError()
		default:
			return 0, nil
		}
	}
	select {
	case <-p.closed:
		return 0, errRTTClosed
	default:
	}
	// The socket ended: usually J-Link Commander exited or lost the target.
	select {
	case <-p.exited:
	case <-time.After(1500 * time.Millisecond):
	}
	select {
	case <-p.exited:
		return 0, p.exitError()
	default:
	}
	return 0, fmt.Errorf("RTT Telnet 连接已断开：%v", e)
}

func (p *commanderPort) exitError() error {
	p.mu.Lock()
	lines := append([]string{}, p.tail...)
	in, out := p.in, p.out
	p.mu.Unlock()
	RTTDiag("rtt commander exited code=%d in=%d out=%d", p.exitCode(), in, out)
	return errors.New("J-Link Commander 已退出。" + explainJLink(lines, p.device, p.exitCode()))
}

func (p *commanderPort) Write(b []byte) (int, error) {
	p.mu.Lock()
	conn := p.conn
	p.mu.Unlock()
	select {
	case <-p.closed:
		return 0, errRTTClosed
	default:
	}
	if conn == nil {
		return 0, errors.New("RTT Telnet 尚未连接。")
	}
	_ = conn.SetWriteDeadline(time.Now().Add(5 * time.Second))
	n, e := conn.Write(b)
	p.mu.Lock()
	p.out += uint64(n)
	p.mu.Unlock()
	if e != nil {
		return n, fmt.Errorf("写入 RTT 下行通道失败：%v", e)
	}
	return n, nil
}

// Drain: J-Link forwards socket bytes into the down-channel buffer; whether
// the firmware reads them is visible only through its reply.
func (p *commanderPort) Drain() error { return nil }

func (p *commanderPort) Close() error {
	p.closeOnce.Do(func() {
		close(p.closed)
		p.mu.Lock()
		conn := p.conn
		p.mu.Unlock()
		if conn != nil {
			conn.Close()
		}
		_, _ = io.WriteString(p.stdin, "exit\r\n")
		select {
		case <-p.exited:
		case <-time.After(2 * time.Second):
			_ = p.cmd.Process.Kill()
			select {
			case <-p.exited:
			case <-time.After(3 * time.Second):
			}
		}
		_ = p.stdin.Close()
		_ = os.Remove(p.script)
		p.mu.Lock()
		in, out := p.in, p.out
		p.mu.Unlock()
		RTTDiag("rtt commander closed in=%d out=%d exit=%d", in, out, p.exitCode())
	})
	return nil
}
